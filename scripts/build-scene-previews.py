"""Build compact, palette-indexed gameplay atlases from the original PNGs (Pillow)."""
import json
from pathlib import Path

from PIL import Image

dist = Path(__file__).resolve().parents[1] / "dist"
assets = dist / "assets"
output = dist / "preview"
output.mkdir(exist_ok=True)
# These sheets are displayed by the room/actor renderer. Wardrobe atlas names
# follow the same convention as the costume definitions.
actors = {
    "rooms-bright-v1", "naiwa-pixel-v2", "mobs-milk-v1", "mobs-stage-v1",
    "mobs-factory-v1", "gunners-actions-v1", "chapter-bosses-v1", "bull-actions-v2",
    "meishu-actions-v1", "family-rescue-v2", "followers-family-v2", "meme-followers-v1",
    "penguins-actions-v1", "phoebe-electrician-v1", "deepseek-actions-v1",
    "gojo-manga-actions-v2", "ghostbuddha-v1",
}
larger = {"rooms-bright-v1", "chapter-bosses-v1", "bull-actions-v2", "meishu-actions-v1"}
sizes = {}
for source in sorted(assets.glob("*.png")):
    if source.stem not in actors and not source.stem.startswith("costume-"):
        continue
    with Image.open(source) as original:
        sizes[source.name] = original.size
        divisor = 2 if source.stem in larger else 3
        size = tuple(round(side / divisor) for side in original.size)
        small = original.convert("RGBA").resize(size, Image.Resampling.LANCZOS)
        small.quantize(colors=192, method=Image.Quantize.FASTOCTREE,
                       dither=Image.Dither.NONE).save(output / source.name, optimize=True)

assert actors.issubset(Path(name).stem for name in sizes)
lines = [f"  {json.dumps(name)}: {list(size)}" for name, size in sizes.items()]
(dist / "preview-sizes.js").write_text(
    "// Original atlas coordinates for the compact PNGs. Generated by build-scene-previews.py.\n"
    + "export const previewSizes = {\n" + ",\n".join(lines) + "\n};\n", encoding="utf-8")
print(f"Built {len(sizes)} gameplay previews.")
